from typing import List, Dict, Optional
from enum import Enum
from pydantic import BaseModel, Field

class ErrorCategory(str, Enum):
    SYNTAX_PARSE = "SYNTAX_PARSE"
    TYPE_SIGNATURE = "TYPE_SIGNATURE"
    GROUNDING_UNSOLVABILITY = "GROUNDING_UNSOLVABILITY"
    SYSTEM_ORACLE_ERROR = "SYSTEM_ORACLE_ERROR"
    HISTORICAL_REGRESSION = "HISTORICAL_REGRESSION"

class RepairOperationType(str, Enum):
    PRECONDITION_RELAXATION = "PRECONDITION_RELAXATION" # Remove over-constraining precondition when goal is unreachable
    PRECONDITION_INSERTION = "PRECONDITION_INSERTION"   # Add missing state constraint
    EFFECT_ALIGNMENT = "EFFECT_ALIGNMENT"               # Add/delete missing state effects
    TYPE_ARITY_ALIGNMENT = "TYPE_ARITY_ALIGNMENT"       # Fix parameter type mismatch, type hierarchy, or predicate arity
    ACTION_ADDITION = "ACTION_ADDITION"                 # Synthesize missing enabling action to complete open causal chain (McAllester & Rosenblitt 1991)
    REGRESSION_BACKWARD_COMPATIBILITY = "REGRESSION_BACKWARD_COMPATIBILITY" # Preserve historical problem solvability
    GENERAL_AST_REPAIR = "GENERAL_AST_REPAIR"           # Catch all for other domain AST repairs

class DiagnosticReport(BaseModel):
    """Structured diagnostic failure item generated by the Triage Node based on Literature (MoRe/AutoStructor)."""
    error_category: ErrorCategory = Field(
        description="High-level category of the failure: SYNTAX_PARSE, TYPE_SIGNATURE, GROUNDING_UNSOLVABILITY, or SYSTEM_ORACLE_ERROR"
    )
    repair_operation_type: RepairOperationType = Field(
        default=RepairOperationType.GENERAL_AST_REPAIR,
        description="Targeted AST operation derived from literature: PRECONDITION_RELAXATION, PRECONDITION_INSERTION, EFFECT_ALIGNMENT, or TYPE_ARITY_ALIGNMENT"
    )
    faulty_element: Optional[str] = Field(
        default=None,
        description="Name of the specific action, predicate, type, or object implicated in the error (if identifiable)"
    )
    raw_log: str = Field(
        description="Exact log text snippet captured from the symbolic oracle"
    )
    suggested_repair_hint: str = Field(
        description="Actionable guidance detailing what structural modifications should be made to resolve the failure"
    )



class PddlActionSchema(BaseModel):
    """Schema definition for individual PDDL actions."""
    action_name: str = Field(
        description="Snake_case identifier for the action, e.g., 'move_robot'"
    )
    parameters: Dict[str, str] = Field(
        description="Map of parameter variables to their types, e.g., {'?r': 'robot', '?from': 'location', '?to': 'location'}"
    )
    preconditions: List[str] = Field(
        description="List of PDDL predicate statements required before execution, e.g., ['(at ?r ?from)', '(connected ?from ?to)']"
    )
    effects: List[str] = Field(
        description="List of PDDL state modifications after execution, e.g., ['(at ?r ?to)', '(not (at ?r ?from))']"
    )

class DomainBlueprint(BaseModel):
    """Phase 2.1 Intermediate Output: Relational Blueprint Schema."""
    domain_name: str = Field(
        default="generated_domain", 
        description="Identifier for the domain, e.g., 'logistics_warehouse'"
    )
    requirements: List[str] = Field(
        default=[":strips", ":typing"], 
        description="List of required PDDL features, e.g., [':strips', ':typing']"
    )
    types: Dict[str, Optional[str]] = Field(
        default_factory=dict,
        description="Map of object types to their parent supertype, e.g., {'robot': 'agent', 'crate': 'object', 'location': None, 'block': 'object'}"
    )
    constants: Dict[str, str] = Field(
        default_factory=dict,
        description="Map of domain-wide constant objects to their types, e.g., {'c1': 'type_name'}"
    )
    predicates: List[str] = Field(
        description="List of formal predicate signatures, e.g., ['(at ?r - robot ?l - location)', '(holding ?r - robot ?c - crate)']"
    )
    actions: List[PddlActionSchema] = Field(
        description="List of all operational action schemas defined in the domain"
    )

class HistoricalProblemCase(BaseModel):
    """Phase 4.1 Maintenance: Stored historical test case for backward compatibility verification."""
    case_id: str = Field(description="Unique identifier for the historical test case, e.g., 'test_case_01'")
    problem_pddl: str = Field(description="Raw PDDL problem string for testing backward compatibility")
    description: Optional[str] = Field(default=None, description="Description of the capability validated by this test case")